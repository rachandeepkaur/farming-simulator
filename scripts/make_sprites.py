def parse(rows: list[str]):
    img = []
    for row in rows:
        line = []
        for ch in row:
            line.append(PAL[ch])
        if len(line) != W:
            raise SystemExit(f"row width {len(line)}: {row}")
        img.append(line)
    if len(img) != W:
        raise SystemExit(f"height {len(img)}")
    return img


def png(img) -> bytes:
    raw = b"".join(b"\x00" + b"".join((bytes(px) if px else b"\x00\x00\x00\x00") for px in row) for row in img)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", W, W, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


